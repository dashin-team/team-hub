const BY_WEEKDAY = {
  1: ACTION,
  2: REJECTION,
  3: CLIENTS,
  4: GROWTH,
  5: TEAM,
};

const ALL = ACTION.concat(REJECTION, CLIENTS, GROWTH, TEAM);

export function dailyQuote(iso) {
  const [year, month, day] = String(iso || "").split("-").map(Number);
  const utc = new Date(Date.UTC(year, month - 1, day));
  const weekday = utc.getUTCDay();
  const pool = weekday === 0 || weekday === 6 ? ALL : BY_WEEKDAY[weekday];
  const dayNumber = Math.floor(utc.getTime() / 86400000);
  return pool[dayNumber % pool.length];
}
